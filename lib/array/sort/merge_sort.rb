# frozen_string_literal: true

module ArraySort
  # Merge sort: O(n log n) comparisons in every case, O(n) extra space, stable.
  #
  # Top-down: sort each half recursively, then merge them. Merging copies the left half into a scratch buffer that
  # is allocated once for the whole sort and writes the merged run back into the array. If the two halves are already
  # in order the merge is skipped, so sorted input costs only O(n) comparisons.
  #
  # @api private
  module MergeSort
    module_function

    def call(array, compare)
      sort_range(array, compare, 0, array.length, Array.new(array.length))
      array
    end

    # Sorts +array[low...high]+.
    def sort_range(array, compare, low, high, buffer)
      return if high - low < 2

      mid = (low + high) / 2
      sort_range(array, compare, low, mid, buffer)
      sort_range(array, compare, mid, high, buffer)
      merge(array, compare, low, mid, high, buffer) if compare.call(array[mid - 1], array[mid]).positive?
    end

    # Merges the sorted runs +array[low...mid]+ and +array[mid...high]+. On ties the left element wins, which is what
    # makes the sort stable.
    def merge(array, compare, low, mid, high, buffer)
      (low...mid).each { |i| buffer[i] = array[i] }
      left = low
      right = mid
      out = low
      while left < mid && right < high
        if compare.call(buffer[left], array[right]).positive?
          array[out] = array[right]
          right += 1
        else
          array[out] = buffer[left]
          left += 1
        end
        out += 1
      end
      # Anything left over on the right is already in place; only leftovers from the left need copying back.
      while left < mid
        array[out] = buffer[left]
        left += 1
        out += 1
      end
    end
  end
end

class Array
  # Returns a new array created by sorting +self+, using merge sort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # @return [Array] the sorted array
  # @raise [ArgumentError] if two elements cannot be compared
  def merge_sort(&)
    ArraySort::Core.sort(self, ArraySort::MergeSort, &)
  end

  # Sorts +self+ in place, using merge sort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # @return [Array] +self+
  # @raise [ArgumentError] if two elements cannot be compared
  # @raise [FrozenError] if +self+ is frozen
  def merge_sort!(&)
    ArraySort::Core.sort!(self, ArraySort::MergeSort, &)
  end

  # Returns a new array created by sorting +self+ with merge sort algorithm, using a set of keys generated by mapping
  # the values in self through the given block. The block is called exactly once per element.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, the sorted array
  # @return [Enumerator] if no block is given, an Enumerator
  def merge_sort_by(&block)
    return to_enum(:merge_sort_by) { size } unless block

    ArraySort::Core.sort_by(self, ArraySort::MergeSort, &block)
  end

  # Sorts +self+ in place with merge sort algorithm, using a set of keys generated by mapping the values in self through
  # the given block. The block is called exactly once per element.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, +self+
  # @return [Enumerator] if no block is given, an Enumerator
  def merge_sort_by!(&block)
    return to_enum(:merge_sort_by!) { size } unless block

    ArraySort::Core.sort_by!(self, ArraySort::MergeSort, &block)
  end
end
