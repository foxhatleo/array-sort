# frozen_string_literal: true

module ArraySort
  # Heap sort: O(n log n) comparisons in every case, O(1) extra space, unstable.
  #
  # Builds a max-heap in place, then repeatedly swaps the largest element to the end of the unsorted region and
  # restores the heap over what remains.
  #
  # @api private
  module HeapSort
    module_function

    def call(array, compare)
      last = array.length - 1
      ((last - 1) / 2).downto(0) { |root| sift_down(array, compare, root, last) }
      last.downto(1) do |boundary|
        array[0], array[boundary] = array[boundary], array[0]
        sift_down(array, compare, 0, boundary - 1)
      end
      array
    end

    # Moves the element at +root+ down until neither child (within +last+) is larger than it.
    def sift_down(array, compare, root, last)
      loop do
        child = (root * 2) + 1
        break if child > last

        child += 1 if child < last && compare.call(array[child], array[child + 1]).negative?
        break unless compare.call(array[root], array[child]).negative?

        array[root], array[child] = array[child], array[root]
        root = child
      end
    end
  end
end

class Array
  # Returns a new array created by sorting +self+, using heap sort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is not guaranteed to be stable. When the comparison of two elements returns +0+, the order of the
  # elements is unpredictable.
  #
  # @return [Array] the sorted array
  # @raise [ArgumentError] if two elements cannot be compared
  def heap_sort(&)
    ArraySort::Core.sort(self, ArraySort::HeapSort, &)
  end

  # Sorts +self+ in place, using heap sort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is not guaranteed to be stable. When the comparison of two elements returns +0+, the order of the
  # elements is unpredictable.
  #
  # @return [Array] +self+
  # @raise [ArgumentError] if two elements cannot be compared
  # @raise [FrozenError] if +self+ is frozen
  def heap_sort!(&)
    ArraySort::Core.sort!(self, ArraySort::HeapSort, &)
  end

  # Returns a new array created by sorting +self+ with heap sort algorithm, using a set of keys generated by mapping the
  # values in self through the given block. The block is called exactly once per element.
  #
  # The result is not guaranteed to be stable. When the comparison of two elements returns +0+, the order of the
  # elements is unpredictable.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, the sorted array
  # @return [Enumerator] if no block is given, an Enumerator
  def heap_sort_by(&block)
    return to_enum(:heap_sort_by) { size } unless block

    ArraySort::Core.sort_by(self, ArraySort::HeapSort, &block)
  end

  # Sorts +self+ in place with heap sort algorithm, using a set of keys generated by mapping the values in self through
  # the given block. The block is called exactly once per element.
  #
  # The result is not guaranteed to be stable. When the comparison of two elements returns +0+, the order of the
  # elements is unpredictable.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, +self+
  # @return [Enumerator] if no block is given, an Enumerator
  def heap_sort_by!(&block)
    return to_enum(:heap_sort_by!) { size } unless block

    ArraySort::Core.sort_by!(self, ArraySort::HeapSort, &block)
  end
end
