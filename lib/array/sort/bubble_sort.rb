# frozen_string_literal: true

module ArraySort
  # Bubble sort: O(n^2) comparisons, O(1) extra space, stable.
  #
  # Each pass remembers where its last swap happened; everything after that point is already in place, so the next
  # pass stops there. An already-sorted array therefore takes a single O(n) pass.
  #
  # @api private
  module BubbleSort
    module_function

    def call(array, compare)
      unsorted_length = array.length
      while unsorted_length > 1
        last_swap = 0
        (1...unsorted_length).each do |i|
          next unless compare.call(array[i - 1], array[i]).positive?

          array[i - 1], array[i] = array[i], array[i - 1]
          last_swap = i
        end
        unsorted_length = last_swap
      end
      array
    end
  end
end

class Array
  # Returns a new array created by sorting +self+, using bubble sort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # @return [Array] the sorted array
  # @raise [ArgumentError] if two elements cannot be compared
  def bubble_sort(&)
    ArraySort::Core.sort(self, ArraySort::BubbleSort, &)
  end

  # Sorts +self+ in place, using bubble sort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # @return [Array] +self+
  # @raise [ArgumentError] if two elements cannot be compared
  # @raise [FrozenError] if +self+ is frozen
  def bubble_sort!(&)
    ArraySort::Core.sort!(self, ArraySort::BubbleSort, &)
  end

  # Returns a new array created by sorting +self+ with bubble sort algorithm, using a set of keys generated by mapping
  # the values in self through the given block. The block is called exactly once per element.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, the sorted array
  # @return [Enumerator] if no block is given, an Enumerator
  def bubble_sort_by(&block)
    return to_enum(:bubble_sort_by) { size } unless block

    ArraySort::Core.sort_by(self, ArraySort::BubbleSort, &block)
  end

  # Sorts +self+ in place with bubble sort algorithm, using a set of keys generated by mapping the values in self
  # through the given block. The block is called exactly once per element.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, +self+
  # @return [Enumerator] if no block is given, an Enumerator
  def bubble_sort_by!(&block)
    return to_enum(:bubble_sort_by!) { size } unless block

    ArraySort::Core.sort_by!(self, ArraySort::BubbleSort, &block)
  end
end
