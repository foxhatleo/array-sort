# frozen_string_literal: true

module ArraySort
  # Quicksort: O(n log n) comparisons on average, O(n^2) in the worst case, O(log n) extra space, unstable.
  #
  # In place, with a randomly chosen pivot so that no particular input (sorted, reversed, organ-pipe...) reliably
  # triggers the quadratic worst case, and a three-way (Dutch national flag) partition so that runs of equal elements
  # are handled in a single pass. Only the smaller partition is sorted recursively and the larger one is handled by the
  # loop, which keeps the recursion depth at O(log n) no matter how unlucky the pivots are.
  #
  # @api private
  module QuickSort
    module_function

    def call(array, compare)
      sort_range(array, compare, 0, array.length - 1)
      array
    end

    # Sorts +array[low..high]+.
    def sort_range(array, compare, low, high)
      while low < high
        less_end, greater_start = partition(array, compare, low, high)
        if less_end - low < high - greater_start
          sort_range(array, compare, low, less_end)
          low = greater_start
        else
          sort_range(array, compare, greater_start, high)
          high = less_end
        end
      end
    end

    # Rearranges +array[low..high]+ into elements less than, equal to, and greater than a pivot. Returns the index of
    # the last "less than" element and the first "greater than" element.
    #
    # The pivot itself always ends up in the "equal" region, so every call makes progress even if the comparison is
    # inconsistent (for example, a block that always returns 1).
    def partition(array, compare, low, high)
      pivot_index = rand(low..high)
      array[low], array[pivot_index] = array[pivot_index], array[low]
      pivot = array[low]

      less = low + 1
      greater = high
      i = low + 1
      while i <= greater
        comparison = compare.call(array[i], pivot)
        if comparison.negative?
          array[less], array[i] = array[i], array[less]
          less += 1
          i += 1
        elsif comparison.positive?
          array[i], array[greater] = array[greater], array[i]
          greater -= 1
        else
          i += 1
        end
      end

      # Move the pivot from the front to the end of the "less than" region, i.e. the start of the "equal" region.
      array[low], array[less - 1] = array[less - 1], array[low]
      [less - 2, greater + 1]
    end
  end
end

class Array
  # Returns a new array created by sorting +self+, using quicksort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is not guaranteed to be stable. When the comparison of two elements returns +0+, the order of the
  # elements is unpredictable.
  #
  # @return [Array] the sorted array
  # @raise [ArgumentError] if two elements cannot be compared
  def quick_sort(&)
    ArraySort::Core.sort(self, ArraySort::QuickSort, &)
  end

  # Sorts +self+ in place, using quicksort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is not guaranteed to be stable. When the comparison of two elements returns +0+, the order of the
  # elements is unpredictable.
  #
  # @return [Array] +self+
  # @raise [ArgumentError] if two elements cannot be compared
  # @raise [FrozenError] if +self+ is frozen
  def quick_sort!(&)
    ArraySort::Core.sort!(self, ArraySort::QuickSort, &)
  end

  # Returns a new array created by sorting +self+ with quicksort algorithm, using a set of keys generated by mapping
  # the values in self through the given block. The block is called exactly once per element.
  #
  # The result is not guaranteed to be stable. When the comparison of two elements returns +0+, the order of the
  # elements is unpredictable.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, the sorted array
  # @return [Enumerator] if no block is given, an Enumerator
  def quick_sort_by(&block)
    return to_enum(:quick_sort_by) { size } unless block

    ArraySort::Core.sort_by(self, ArraySort::QuickSort, &block)
  end

  # Sorts +self+ in place with quicksort algorithm, using a set of keys generated by mapping the values in self through
  # the given block. The block is called exactly once per element.
  #
  # The result is not guaranteed to be stable. When the comparison of two elements returns +0+, the order of the
  # elements is unpredictable.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, +self+
  # @return [Enumerator] if no block is given, an Enumerator
  def quick_sort_by!(&block)
    return to_enum(:quick_sort_by!) { size } unless block

    ArraySort::Core.sort_by!(self, ArraySort::QuickSort, &block)
  end
end
