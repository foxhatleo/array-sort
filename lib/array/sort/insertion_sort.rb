# frozen_string_literal: true

module ArraySort
  # Insertion sort: O(n^2) comparisons in the worst case, O(n) on nearly-sorted input, O(1) extra space, stable.
  #
  # Larger elements are shifted one slot to the right until the gap reaches the correct position for the element
  # being inserted, which takes fewer writes than swapping it into place pair by pair.
  #
  # @api private
  module InsertionSort
    module_function

    def call(array, compare)
      (1...array.length).each do |i|
        element = array[i]
        j = i
        while j.positive? && compare.call(array[j - 1], element).positive?
          array[j] = array[j - 1]
          j -= 1
        end
        array[j] = element
      end
      array
    end
  end
end

class Array
  # Returns a new array created by sorting +self+, using insertion sort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # @return [Array] the sorted array
  # @raise [ArgumentError] if two elements cannot be compared
  def insertion_sort(&)
    ArraySort::Core.sort(self, ArraySort::InsertionSort, &)
  end

  # Sorts +self+ in place, using insertion sort algorithm.
  #
  # Comparisons for the sort will be done using the <=> operator or using an optional code block.
  #
  # The block must implement a comparison between +a+ and +b+ and return an integer less than 0 when +b+ follows +a+,
  # +0+ when +a+ and +b+ are equivalent, or an integer greater than 0 when +a+ follows +b+.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # @return [Array] +self+
  # @raise [ArgumentError] if two elements cannot be compared
  # @raise [FrozenError] if +self+ is frozen
  def insertion_sort!(&)
    ArraySort::Core.sort!(self, ArraySort::InsertionSort, &)
  end

  # Returns a new array created by sorting +self+ with insertion sort algorithm, using a set of keys generated by
  # mapping the values in self through the given block. The block is called exactly once per element.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, the sorted array
  # @return [Enumerator] if no block is given, an Enumerator
  def insertion_sort_by(&block)
    return to_enum(:insertion_sort_by) { size } unless block

    ArraySort::Core.sort_by(self, ArraySort::InsertionSort, &block)
  end

  # Sorts +self+ in place with insertion sort algorithm, using a set of keys generated by mapping the values in self
  # through the given block. The block is called exactly once per element.
  #
  # The result is guaranteed to be stable. When the comparison of two elements returns +0+, the order of the elements
  # will be preserved.
  #
  # If no block is given, an Enumerator is returned instead.
  #
  # @return [Array] if a block is given, +self+
  # @return [Enumerator] if no block is given, an Enumerator
  def insertion_sort_by!(&block)
    return to_enum(:insertion_sort_by!) { size } unless block

    ArraySort::Core.sort_by!(self, ArraySort::InsertionSort, &block)
  end
end
